import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { cypher } from 'conceal-lib-js';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { buildNative, root, skipNative } from './helpers/native';

type Cipher = 'chacha8' | 'chacha12' | 'chacha20';
type Case = {
  id: 'A0' | 'A1' | 'AN' | 'C-pad';
  cipher: Cipher;
  index: string;
  plaintext: 'short' | 'long';
  nativeIv: string;
  oracleNonce: string;
  ciphertext: string;
};
type Fixture = { oracle: string; key: string; plaintexts: Record<string, string>; cases: Case[] };

const fixture: Fixture = JSON.parse(readFileSync(join(root, 'test/fixtures/chacha.json'), 'utf8'));
const key = Buffer.from(fixture.key, 'hex');
const pt = (name: string) => Buffer.from(fixture.plaintexts[name], 'hex');
const hex = (u8: Uint8Array) => Buffer.from(u8).toString('hex');

const be8 = (index: string) => {
  const b = Buffer.alloc(8);
  b.writeBigUInt64BE(BigInt(index));
  return b;
};

describe('conceal-lib-js oracle', () => {
  const nonce = Buffer.alloc(12, 7);
  const data = pt('long');

  it.each(['chacha8', 'chacha12', 'chacha20'] as Cipher[])(
    '%s round-trips and is deterministic',
    (c) => {
      const ct = cypher[c](key, nonce, data);
      expect(hex(cypher[c](key, nonce, data))).toBe(hex(ct));
      expect(hex(cypher[c](key, nonce, ct))).toBe(hex(data));
    }
  );

  it('rejects an 8-byte nonce (IETF only)', () => {
    expect(() => cypher.chacha8(key, Buffer.alloc(8), data)).toThrow();
  });
});

describe('fixtures', () => {
  it.each(fixture.cases.map((c) => [`${c.id} ${c.cipher} ${c.plaintext} i=${c.index}`, c]))(
    'match live oracle: %s',
    (_, c) => {
      const out = cypher[c.cipher](key, Buffer.from(c.oracleNonce, 'hex'), pt(c.plaintext));
      expect(hex(out)).toBe(c.ciphertext);
    }
  );

  it.each(fixture.cases.map((c) => [`${c.id} ${c.cipher} ${c.plaintext} i=${c.index}`, c]))(
    'nonce construction: %s',
    (_, c) => {
      expect(c.nativeIv).toBe(hex(be8(c.index)));
      const expected =
        c.id === 'C-pad'
          ? Buffer.concat([be8(c.index), Buffer.alloc(4)])
          : Buffer.concat([Buffer.alloc(4), be8(c.index)]);
      expect(c.oracleNonce).toBe(hex(expected));
    }
  );

  it('C-pad (2fa JS-fallback buffer fed to IETF) differs from the SDK 12-byte BE layout', () => {
    for (const c of fixture.cases.filter((x) => x.id === 'C-pad')) {
      const sdk = fixture.cases.find(
        (x) => x.id === 'A1' && x.cipher === c.cipher && x.plaintext === c.plaintext
      );
      expect(sdk).toBeDefined();
      expect(c.ciphertext).not.toBe(sdk?.ciphertext);
    }
  });
});

describe.skipIf(skipNative)('native cpp/chacha*.c (as-is, 8-byte IV API)', () => {
  let native: ReturnType<typeof buildNative>;
  const rows: string[] = [];

  const runNative = (rounds: 8 | 12, iv: string, data: Buffer) =>
    native.run(rounds, fixture.key, iv, data.toString('hex'));

  beforeAll(() => {
    native = buildNative();
  });

  afterAll(() => {
    native?.cleanup();
    if (rows.length === 0) return;
    const report = [
      '# ChaCha parity report (as-is)',
      '',
      `Generated by \`npm test\`. Oracle: ${fixture.oracle}.`,
      'Native: `cpp/chacha8.c` / `cpp/chacha12.c` via `chacha8_xor` / `chacha12_xor` (8-byte IV, 64-bit counter).',
      '',
      '| Case | Cipher | Plaintext | Index | Native IV | Oracle nonce | Expected | Result |',
      '|------|--------|-----------|-------|-----------|--------------|----------|--------|',
      ...rows,
      '',
    ].join('\n');
    writeFileSync(join(root, 'test/parity-report.md'), report);
  });

  const nativeCases = fixture.cases.filter((c) => c.cipher !== 'chacha20');

  it.each(nativeCases.map((c) => [`${c.id} ${c.cipher} ${c.plaintext} i=${c.index}`, c]))(
    '%s',
    (_, c) => {
      const res = runNative(c.cipher === 'chacha8' ? 8 : 12, c.nativeIv, pt(c.plaintext));
      expect(res.status).toBe(0);
      const match = res.stdout.trim() === c.ciphertext;
      const expected = c.id === 'C-pad' ? 'differ' : 'match';
      const asExpected = (expected === 'match') === match;
      rows.push(
        `| ${c.id} | ${c.cipher} | ${c.plaintext} | ${c.index} | \`${c.nativeIv}\` | \`${c.oracleNonce}\` | ${expected} | ${match ? 'match' : 'differ'}${asExpected ? '' : ' (UNEXPECTED)'} |`
      );
      expect(asExpected).toBe(true);
    }
  );

  it('B-api: 12-byte nonce is rejected by the native size check', () => {
    const res = runNative(8, '00'.repeat(12), pt('short'));
    expect(res.status).toBe(3);
    expect(res.stderr).toMatch(/IV must be exactly 8 bytes/);
    rows.push(
      '| B-api | chacha8 | short | 0 | — | `000000000000000000000000` | reject | rejected (`IV must be exactly 8 bytes`) |'
    );
  });
});
